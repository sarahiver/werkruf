-- 10-supabase-stubs.sql
--
-- Die Schemas, die Supabase mitbringt und die pg_dump nicht liefert.
--
-- WARUM ES SIE BRAUCHT
--
-- Die Baseline entstand mit --schema=public. Alles, was Supabase
-- daneben betreibt, fehlt darin: auth, cron, net, vault, storage.
-- Die Migrationen greifen darauf zu — ohne diese Objekte scheitern
-- vierzehn von sechsunddreissig, meist mit
--
--   ERROR:  schema "auth" does not exist
--
-- WAS EIN STUB HIER IST UND WAS NICHT
--
-- Ein Stub ist die kleinste Form, die den produktiven Code laden und
-- laufen laesst — nicht ein Nachbau von Supabase. Er darf
--
--   Tabellen und Funktionen bereitstellen, auf die Produktionscode
--   namentlich zugreift
--
-- und darf nicht
--
--   eine fachliche Aussage treffen, die in Produktion anders ausfaellt
--
-- Deshalb geben die Funktionen hier bewusst nichts Sinnvolles zurueck:
-- auth.uid() ist null, net.http_post() tut nichts, cron.schedule()
-- schreibt nur eine Zeile. Ein Test, der auf einem Stub-Ergebnis
-- aufbaut, testet den Stub — das soll auffallen, nicht durchrutschen.
--
-- ZENTRAL, NICHT JE TESTDATEI
--
-- Vorher baute jede Testdatei sich zusammen, was sie brauchte. Dadurch
-- hatten zwei Tests unterschiedliche Vorstellungen derselben Tabelle.
-- Diese Datei ist die einzige Stelle, an der Stubs entstehen.
--
-- Wiederholbar.

/* ═══════════════════════════════════════════════════════════════
   auth — Supabase Auth
   ═══════════════════════════════════════════════════════════════ */

create schema if not exists auth authorization supabase_auth_admin;

/*
 * auth.users
 *
 * Nur die Spalten, die Produktionscode und Tests nennen: id und email.
 * Die echte Tabelle hat Dutzende weitere; sie hier zu erfinden hiesse,
 * ein Schema zu behaupten, das niemand geprueft hat.
 *
 * Der Primaerschluessel ist Pflicht, nicht Zierde: zwei Migrationen
 * verweisen mit references auth.users(id) darauf.
 */
create table if not exists auth.users (
  id    uuid primary key default gen_random_uuid(),
  email text
);

/*
 * Der aufrufende Nutzer.
 *
 * In Produktion liest das den JWT. Lokal gibt es keinen, also null.
 * Folge: RLS-Policies, die auth.uid() verwenden, lassen lokal nichts
 * durch. Tests laufen deshalb als Eigentuemer der Tabellen, nicht als
 * authenticated — und RLS-Verhalten wird hier nicht geprueft. Wer es
 * pruefen will, braucht eine echte Supabase-Instanz; der Test
 * customer_isolation_sessions.mjs tut genau das.
 */
create or replace function auth.uid()
returns uuid
language sql
stable
as $$ select null::uuid $$;

create or replace function auth.jwt()
returns jsonb
language sql
stable
as $$ select '{}'::jsonb $$;

create or replace function auth.role()
returns text
language sql
stable
as $$ select current_user::text $$;

/* ═══════════════════════════════════════════════════════════════
   cron — pg_cron
   ═══════════════════════════════════════════════════════════════ */

create schema if not exists cron;

/*
 * cron.job
 *
 * Mehrere Migrationen fragen diese Tabelle ab, um zu entscheiden, ob
 * ein Job existiert und aktiv ist. Spalten wie in pg_cron.
 */
create table if not exists cron.job (
  jobid    bigint generated by default as identity primary key,
  schedule text not null,
  command  text not null,
  nodename text   not null default 'localhost',
  nodeport integer not null default 5432,
  database text   not null default pg_catalog.current_database(),
  username text   not null default pg_catalog.current_user(),
  active   boolean not null default true,
  jobname  text unique
);

create table if not exists cron.job_run_details (
  jobid          bigint,
  runid          bigint generated by default as identity primary key,
  job_pid        integer,
  database       text,
  username       text,
  command        text,
  status         text,
  return_message text,
  start_time     timestamptz,
  end_time       timestamptz
);

/*
 * cron.schedule / cron.unschedule
 *
 * Die echten Funktionen richten einen Hintergrundjob ein. Hier wird nur
 * die Zeile geschrieben beziehungsweise entfernt — genau so viel, dass
 * eine Migration, die einen Job anlegt, danach ihre eigene Pruefung
 * ("existiert der Job?") besteht.
 *
 * Der Job laeuft lokal nicht. Das ist richtig so: ein Test, der auf
 * einen wirklich feuernden Cron wartet, wuerde nie fertig.
 */
create or replace function cron.schedule(
  p_job_name  text,
  p_schedule  text,
  p_command   text
)
returns bigint
language plpgsql
as $$
declare v_id bigint;
begin
  delete from cron.job where jobname = p_job_name;
  insert into cron.job (schedule, command, jobname)
  values (p_schedule, p_command, p_job_name)
  returning jobid into v_id;
  return v_id;
end $$;

create or replace function cron.unschedule(p_job_name text)
returns boolean
language plpgsql
as $$
begin
  delete from cron.job where jobname = p_job_name;
  return true;
end $$;

create or replace function cron.unschedule(p_job_id bigint)
returns boolean
language plpgsql
as $$
begin
  delete from cron.job where jobid = p_job_id;
  return true;
end $$;

/* ═══════════════════════════════════════════════════════════════
   net — pg_net
   ═══════════════════════════════════════════════════════════════ */

create schema if not exists net;

/*
 * net._http_response
 *
 * Die Alarmlogik zaehlt hier Antworten der letzten dreissig Minuten, um
 * zu erkennen, ob pg_net ueberhaupt noch arbeitet. Lokal bleibt die
 * Tabelle leer — der Alarm "pg_net still" wuerde also lokal feuern.
 * Tests, die das pruefen, muessen selbst Zeilen einfuegen.
 */
create table if not exists net._http_response (
  id          bigint generated by default as identity primary key,
  status_code integer,
  content_type text,
  headers     jsonb,
  content     text,
  timed_out   boolean,
  error_msg   text,
  created     timestamptz not null default pg_catalog.now()
);

create or replace function net.http_post(
  url     text,
  body    jsonb   default '{}'::jsonb,
  params  jsonb   default '{}'::jsonb,
  headers jsonb   default '{}'::jsonb,
  timeout_milliseconds integer default 5000
)
returns bigint
language sql
as $$ select 0::bigint $$;

create or replace function net.http_get(
  url     text,
  params  jsonb   default '{}'::jsonb,
  headers jsonb   default '{}'::jsonb,
  timeout_milliseconds integer default 5000
)
returns bigint
language sql
as $$ select 0::bigint $$;

/* ═══════════════════════════════════════════════════════════════
   vault — Supabase Vault
   ═══════════════════════════════════════════════════════════════ */

create schema if not exists vault;

/*
 * vault.decrypted_secrets
 *
 * In Produktion eine Sicht auf entschluesselte Geheimnisse. Lokal eine
 * leere Tabelle: ein Testaufbau soll keine Geheimnisse halten, auch
 * keine erfundenen. Code, der ein Geheimnis braucht, bekommt null und
 * muss damit umgehen — genau wie in Produktion, wenn es fehlt.
 */
create table if not exists vault.decrypted_secrets (
  id               uuid primary key default gen_random_uuid(),
  name             text unique,
  description      text,
  secret           text,
  decrypted_secret text,
  created_at       timestamptz not null default pg_catalog.now(),
  updated_at       timestamptz not null default pg_catalog.now()
);

/* ═══════════════════════════════════════════════════════════════
   storage — Supabase Storage
   ═══════════════════════════════════════════════════════════════ */

create schema if not exists storage;

create table if not exists storage.buckets (
  id                 text primary key,
  name               text not null,
  owner              uuid,
  public             boolean not null default false,
  file_size_limit    bigint,
  allowed_mime_types text[],
  created_at         timestamptz not null default pg_catalog.now(),
  updated_at         timestamptz not null default pg_catalog.now()
);

create table if not exists storage.objects (
  id         uuid primary key default gen_random_uuid(),
  bucket_id  text references storage.buckets(id),
  name       text,
  owner      uuid,
  metadata   jsonb,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now()
);

/* ═══════════════════════════════════════════════════════════════
   RECHTE
   ═══════════════════════════════════════════════════════════════ */

grant usage on schema auth, cron, net, vault, storage to service_role;
grant usage on schema auth to authenticated, anon;
grant select on auth.users to service_role;
