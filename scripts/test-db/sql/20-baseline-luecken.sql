-- ═══════════════════════════════════════════════════════════════
--
-- production-baseline-2026-09-22.sql ist abgeschnitten. Die Datei endet
-- mitten in einer CREATE VIEW. pg_dump schreibt Schluessel, Indizes,
-- Trigger, Policies und Sequenzen NACH den Tabellen und Sichten — all
-- das fehlt deshalb vollstaendig:
--
--   PRIMARY KEY        0 ×
--   FOREIGN KEY        0 ×
--   CREATE INDEX       0 ×
--   CREATE TRIGGER     0 ×
--   CREATE POLICY      0 ×
--   CREATE SEQUENCE    0 ×
--
-- Ohne Primaerschluessel scheitern vierzehn Migrationen, weil ihre
-- Fremdschluessel kein Ziel finden:
--
--   ERROR:  there is no unique constraint matching given keys
--           for referenced table "google_locations"
--
-- ═══════════════════════════════════════════════════════════════
-- WAS HIER ERLAUBT IST UND WAS NICHT
-- ═══════════════════════════════════════════════════════════════
--
-- Jeder Eintrag unten muss BELEGT sein: eine Stelle im produktiven Code
-- oder in der Baseline, die beweist, dass Produktion diese Eindeutigkeit
-- besitzt. Ein Fremdschluessel auf google_locations(id) kann nur
-- existieren, wenn dort ein Unique-Constraint liegt — das ist ein
-- Beweis, keine Annahme.
--
-- Nicht erlaubt ist, hier irgendetwas zu ergaenzen, weil es sinnvoll
-- aussieht. Jede Zeile nennt ihren Beleg. Was keinen hat, kommt nicht
-- hierher, sondern auf die Liste fuer G2.
--
-- Diese Datei ist deshalb ausdruecklich TESTAUFBAU und nicht
-- Produktionsschema. Sie behauptet nicht, vollstaendig zu sein — sie
-- behauptet nur, dass ohne sie nichts laeuft. Die offenen Punkte stehen
-- in docs/testing/baseline-luecken.md.
--
-- Wiederholbar.

/* ═══════════════════════════════════════════════════════════════
   1 — IDENTITAET FUER recommendation_events.id
   ═══════════════════════════════════════════════════════════════ */

/*
 * Beleg: Die Baseline definiert
 *
 *   id bigint NOT NULL
 *
 * ohne Default, und public.record_recommendation_action() fuegt ohne id
 * ein. Eine Spalte, die beides ist, kann in Produktion nur Identity oder
 * Serial sein; pg_dump schreibt die Sequenz getrennt, und dieser Teil ist
 * abgeschnitten.
 *
 * (Hier stand bis 12.10.2026 log_recommendation_event() als Beleg. Diese
 * Funktion existiert nicht. Die Schlussfolgerung war richtig, der Beleg
 * falsch — gefunden in G2.)
 *
 * Ob Produktion GENERATED ALWAYS oder BY DEFAULT verwendet, steht nicht
 * in der Baseline. BY DEFAULT ist die vorsichtigere Wahl: sie laesst
 * beides zu, also auch einen Test, der eine id explizit setzt.
 */
do $$
begin
  /* Beide Pruefungen auf die Spalte id. Ein frueherer Entwurf fragte
     nur, ob die TABELLE irgendeinen Default hat — occurred_at hat
     einen, also tat der Block nichts, und recommendation_events.id
     blieb ohne Default. Der Test fiel erst zwanzig Schritte spaeter
     auf, als "null value in column id". */
  if not exists (
    select 1 from pg_catalog.pg_attribute a
     where a.attrelid    = 'public.recommendation_events'::regclass
       and a.attname     = 'id'
       and a.attidentity <> ''
  ) and not exists (
    select 1 from pg_catalog.pg_attrdef d
      join pg_catalog.pg_attribute a
        on a.attrelid = d.adrelid and a.attnum = d.adnum
     where d.adrelid = 'public.recommendation_events'::regclass
       and a.attname = 'id'
  ) then
    alter table public.recommendation_events
      alter column id add generated by default as identity;
  end if;
end $$;

/* ═══════════════════════════════════════════════════════════════
   2 — PRIMAERSCHLUESSEL
   ═══════════════════════════════════════════════════════════════ */

/*
 * Jeder hier ist Ziel eines Fremdschluessels oder eines ON CONFLICT im
 * produktiven Code. Die Belege stehen an jeder Zeile.
 *
 * Das Muster prueft erst, ob die Tabelle schon einen Primaerschluessel
 * hat. Sobald die Baseline durch einen vollstaendigen Dump ersetzt wird,
 * tut diese Datei dann nichts mehr — sie verschwindet von selbst, ohne
 * dass jemand daran denken muss.
 */
do $$
declare
  v_ziel record;
begin
  for v_ziel in
    select * from (values
      -- Tabelle,                   Spalten,              Beleg
      ('google_locations',          'id',
       '4 × references public.google_locations(id) in Migrationen 20260930140000, 20260930160000 (2 ×), 20261005140000'),
      ('events',                    'id',
       'references public.events(id) in 20261005140000_action_tokens.sql:56'),
      ('email_queue',               'id',
       'references public.email_queue(id) in 20260928100000_public_profile_reports.sql:13'),
      ('leads',                     'id',
       'references public.leads(id) in 20260928100000_public_profile_reports.sql:5'),
      ('google_accounts',           'id',
       'on conflict (id) in supabase/tests — und Ziel von google_locations.account_id'),
      ('user_profiles',             'id',
       'on conflict (id) in 5 Testdateien; Spalte ist uuid NOT NULL ohne Default, also Fremdschluessel auf auth.users'),
      ('recommendation_events',     'id',
       'id bigint NOT NULL; Identity oben ergaenzt'),
      ('sync_jobs',                 'id',
       'returning id in enqueue_sync_job(), Baseline Zeile 748'),
      ('sync_runs',                 'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('google_reviews',            'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('review_replies',            'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('business_photos',           'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('oauth_tokens',              'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('ai_usage_log',              'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('audit_logs',                'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline'),
      ('weekly_snapshots',          'id',
       'id uuid DEFAULT gen_random_uuid() NOT NULL, Baseline')
    ) as z(tabelle, spalten, beleg)
  loop
    if not exists (
      select 1 from pg_catalog.pg_constraint c
       where c.conrelid = ('public.' || v_ziel.tabelle)::regclass
         and c.contype  = 'p'
    ) then
      execute pg_catalog.format(
        'alter table public.%I add primary key (%s)',
        v_ziel.tabelle, v_ziel.spalten);
      raise notice '[testaufbau] Primaerschluessel ergaenzt: %(%) — %',
        v_ziel.tabelle, v_ziel.spalten, v_ziel.beleg;
    end if;
  end loop;
end $$;

/* ═══════════════════════════════════════════════════════════════
   3 — EINDEUTIGKEIT, DIE ON CONFLICT VORAUSSETZT
   ═══════════════════════════════════════════════════════════════ */

/*
 * ON CONFLICT (spalten) braucht einen passenden Unique-Index, sonst:
 *
 *   ERROR:  there is no unique or exclusion constraint matching
 *           the ON CONFLICT specification
 *
 * Jede Klausel im produktiven Code ist daher ein Beweis, dass der Index
 * in Produktion existiert.
 */

/* Beleg: on conflict (dedupe_key) in schedule_communications(). */
create unique index if not exists email_queue_dedupe_key_idx
  on public.email_queue (dedupe_key);

/* Beleg: on conflict (user_id) in ensure_notification_preferences(). */
create unique index if not exists notification_preferences_user_idx
  on public.notification_preferences (user_id);

/* Beleg: on conflict (alert_key) in der Alarmlogik. */
create unique index if not exists ops_alert_log_key_idx
  on public.ops_alert_log (alert_key);

/* Beleg: on conflict (user_id, week_start) beim Wochenschnappschuss. */
create unique index if not exists weekly_snapshots_user_week_idx
  on public.weekly_snapshots (user_id, week_start);

/*
 * sync_jobs: zwei partielle Indizes.
 *
 * Beleg: enqueue_sync_job() in der Baseline, Zeilen 745 und 759. Die
 * WHERE-Klauseln sind von dort uebernommen, nicht gewaehlt — ein
 * partieller ON CONFLICT trifft nur, wenn das Praedikat des Index
 * identisch ist.
 */
create unique index if not exists sync_jobs_reply_aktiv_idx
  on public.sync_jobs (job_type, (payload ->> 'replyId'))
  where status in ('queued', 'running') and job_type = 'publish_reply';

create unique index if not exists sync_jobs_location_aktiv_idx
  on public.sync_jobs (job_type, location_id)
  where status in ('queued', 'running')
    and location_id is not null
    and job_type in ('sync_reviews', 'sync_locations', 'sync_insights');

/* ═══════════════════════════════════════════════════════════════
   4 — FREMDSCHLUESSEL, DIE TESTS SICHTBAR MACHEN SOLLEN
   ═══════════════════════════════════════════════════════════════ */

/*
 * Nur die beiden, um die es in G1 ging — und nur, weil der Beleg
 * eindeutig ist:
 *
 *   google_locations.account_id   uuid NOT NULL
 *   google_accounts.user_id       uuid NOT NULL
 *
 * Eine Pflichtspalte namens account_id in einer Tabelle, deren Nachbar
 * google_accounts heisst, ist in Produktion ein Fremdschluessel. Ohne
 * ihn koennen Tests eine Location an ein Konto haengen, das es nicht
 * gibt — genau die Art Luecke, die G1 schliessen soll.
 *
 * Die uebrigen Fremdschluessel der Baseline bleiben offen und stehen in
 * docs/testing/baseline-luecken.md. Sie zu erraten waere das, was
 * Punkt 24 des Auftrags verbietet.
 */
do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_constraint
     where conname = 'google_accounts_user_id_fkey'
       and conrelid = 'public.google_accounts'::regclass
  ) then
    alter table public.google_accounts
      add constraint google_accounts_user_id_fkey
      foreign key (user_id) references auth.users(id) on delete cascade;
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
     where conname = 'google_locations_account_id_fkey'
       and conrelid = 'public.google_locations'::regclass
  ) then
    alter table public.google_locations
      add constraint google_locations_account_id_fkey
      foreign key (account_id) references public.google_accounts(id) on delete cascade;
  end if;

  if not exists (
    select 1 from pg_catalog.pg_constraint
     where conname = 'google_locations_user_id_fkey'
       and conrelid = 'public.google_locations'::regclass
  ) then
    alter table public.google_locations
      add constraint google_locations_user_id_fkey
      foreign key (user_id) references auth.users(id) on delete cascade;
  end if;
end $$;

